import { _electron as electron } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { Game } from '../src/engine.mjs';
const profile=path.resolve('.tmp/crystal-ui-'+Date.now());
await fs.mkdir(profile,{recursive:true});
const g=new Game(84);g.beginBattle([{uid:900,enemy:'mendingTutor',restless:0}]);g.s.hp=40;
const crystal=g.addItem('liquidCrystal'),potion=g.addItem('healingSap'),plain=g.addItem('healingSap');
delete g.s.checkpoint;
await fs.writeFile(profile+'/save.json',JSON.stringify(g.s));
await fs.writeFile(profile+'/settings.json',JSON.stringify({width:1280,fast:true}));
const app=await electron.launch({executablePath:path.resolve('release/Astrata/Astrata.exe'),args:['--user-data-dir='+profile]});
const report={checks:[],errors:[]};
try {
 const p=await app.firstWindow();p.on('pageerror',e=>report.errors.push(e.message));
 await p.locator('[data-ui="continue"]').click();
 await p.locator('[data-ui="inventory"]').click();
 const source=p.locator('.dialog [data-item-detail="'+crystal.uid+'"]');
 await source.locator('img').evaluate(img=>img.decode());
 await source.dragTo(p.locator('.dialog [data-item-detail="'+potion.uid+'"]'));
 await p.locator('.dialog [data-item-detail="'+potion.uid+'"].crystal-enhanced').waitFor();
 assert.equal(await p.locator('.dialog [data-item-detail="'+crystal.uid+'"]').count(),0);
 await fs.mkdir('reports/screenshots/liquid-crystal',{recursive:true});
 await p.screenshot({path:'reports/screenshots/liquid-crystal/satchel.png'});
 await p.locator('.dialog-close').click();
 assert.match(await p.locator('[data-consumable-uid="'+potion.uid+'"]').textContent(),/10 HP/);
 assert.match(await p.locator('[data-consumable-uid="'+plain.uid+'"]').textContent(),/5 HP/);
 await p.locator('[data-consumable-view="'+potion.uid+'"]').click();
 assert.match(await p.locator('.dialog').textContent(),/10 HP/);
 await p.locator('.dialog-close').click();
 await p.locator('[data-consumable-uid="'+potion.uid+'"] .consumable-use').click();
 await p.waitForFunction(()=>!document.querySelector('.presentation-bar'));
 assert.equal(await p.locator('[data-consumable-uid="'+potion.uid+'"]').count(),0);
 assert.equal(await p.locator('.consumable-use:not([disabled])').count(),0);
 await p.screenshot({path:'reports/screenshots/liquid-crystal/used.png'});
 const runs=await fs.readdir(profile+'/runs',{withFileTypes:true});
 const run=runs.find(x=>x.isDirectory()&&x.name!=='builds').name;
 const raw=JSON.parse(await fs.readFile(profile+'/runs/'+run+'/latest.json','utf8')),s=raw.state||raw;
 assert.equal(s.hp,50);assert.equal(s.stats.potionsEnhanced.length,1);
 assert.equal(s.stats.consumablesUsed.at(-1).effects.heal,10);
 report.checks.push('Packaged art loads; real Satchel drag combines and removes vial; enhanced badge and 10 HP preview visible; plain 5 HP group stays separate; details accurate; use heals 10, spends one-use allowance, archives effect.');
 assert.deepEqual(report.errors,[]);
} finally {await app.close();}
await fs.writeFile('reports/liquid-crystal-ui-verification.json',JSON.stringify(report,null,2));console.log(report);

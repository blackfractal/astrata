import test from 'node:test';
import assert from 'node:assert/strict';
import { Game, gridNeighbors, attunementElements, squarePattern } from '../src/engine.mjs';
import { cardFrozen, cardSevered, startRepairs } from '../src/corruptions.mjs';
import { boardConnections } from '../src/board-interactions.mjs';
const setup = () => {
  const g = new Game(84);
  g.s.stratum = 2;
  g.beginBattle([{ uid: g.uid(), enemy: 'mendingTutor', restless: 0 }]);
  const b = g.s.battle;
  b.grid = Array.from({length:42}, () => []);
  b.corruptions = { 8: {kind:'insanity', uid:g.uid(), value:4, source:b.enemies[0].uid} };
  b.channel = b.focus = 10;
  return g;
};
const put = (g, id, slot) => (g.s.battle.grid[slot] = [g.instance(g.newCard(id))])[0];
const act = (g, type, props) => {
  const a = g.legal().find(a => a.type === type && Object.entries(props).every(([k,v]) => a[k] === v));
  assert.ok(a, JSON.stringify({type,...props}));
  g.act(a);
};
test('Insanity disables activation and both directions of adjacency, patterns and attunement', () => {
  const g = setup(), b = g.s.battle;
  const c = put(g, 'water', 8), blast = put(g, 'blast', 9), square = put(g, 'square', 15);
  put(g, 'shield', 16);
  b.phase = 'activate';
  assert.equal(g.activationAvailable(c,8), false);
  assert.ok(!g.legal().some(a => a.type === 'activate' && a.slot === 8));
  assert.deepEqual(gridNeighbors(b,8), []);
  assert.ok(!gridNeighbors(b,9).includes(8));
  assert.deepEqual(attunementElements(b,blast,9), ['Arcane']);
  assert.deepEqual(squarePattern(b,square,15), []);
  assert.ok(!boardConnections(b).some(l => l.from === 8 || l.to === 8));
  delete b.corruptions[8];
  assert.equal(g.activationAvailable(c,8), true);
  assert.ok(attunementElements(b,blast,9).includes('Water'));
  assert.equal(squarePattern(b,square,15).length,4);
});
test('Covered Insanity suppresses and resets HP loss but derived Freeze/Sever survive reload and turn changes', () => {
  const g = setup(), b = g.s.battle, c = put(g,'blast',8);
  const hp = g.s.hp;
  startRepairs(g);
  assert.equal(g.s.hp,hp);
  assert.equal(b.corruptions[8].value,1);
  assert.equal(c.freeze,0);
  assert.equal(c.sever,false);
  const loaded = new Game(0,g.s);
  loaded.s.battle.turn += 3;
  const cover = loaded.s.battle.grid[8][0];
  assert.equal(cardFrozen(loaded.s.battle,cover,8),true);
  assert.equal(cardSevered(loaded.s.battle,cover,8),true);
  act(loaded,'recall',{slot:8});
  startRepairs(loaded);
  assert.equal(loaded.s.hp,hp-1);
  assert.equal(loaded.s.battle.corruptions[8].value,2);
});
test('Elves on Insanity cannot Mend, adjacent Elves repair it and restore the cover immediately', () => {
  const g = setup(), b = g.s.battle;
  const trapped = put(g,'elves',8), helper = put(g,'elves',9);
  b.phase='activate';
  assert.ok(!g.legal().some(a=>a.type==='activate' && a.slot===8));
  act(g,'activate',{slot:9,cardTarget:8,repairKind:'insanity'});
  assert.equal(b.corruptions[8],undefined);
  assert.equal(helper.used,1);
  assert.equal(g.activationAvailable(trapped,8),true);
  assert.ok(gridNeighbors(b,8).includes(9));
});
test('Repairing Insanity does not erase independent Freeze or Sever statuses', () => {
  const g=setup(), b=g.s.battle, c=put(g,'blast',8);
  c.freeze=b.turn+2;
  c.sever=true;
  put(g,'elves',9);
  b.phase='activate';
  act(g,'activate',{slot:9,cardTarget:8,repairKind:'insanity'});
  assert.equal(cardFrozen(b,c,8),true);
  assert.equal(cardSevered(b,c,8),true);
});
test('An existing Mend job pauses while its Elves cover Insanity', () => {
  const g=setup(), b=g.s.battle, c=put(g,'elves',8);
  const q={kind:'hole',uid:g.uid(),source:b.enemies[0].uid};
  b.corruptions[9]=q;
  c.mending={slot:9,kind:'hole',corruptionUid:q.uid,due:b.turn};
  startRepairs(g);
  assert.ok(b.corruptions[9]);
  assert.ok(c.mending);
  delete b.corruptions[8];
  startRepairs(g);
  assert.equal(b.corruptions[9],undefined);
});
